def build_workbook(mi: ModelInputs, path: Path | str) -> Path:
    """Assemble the workbook from a ModelInputs bundle and save it. Pure (no
    network) so the offline tests drive it directly with synthetic data."""
    wb = Workbook()
    names: dict[str, tuple[str, str]] = {}
    s = _seeds(mi)
    bank = mi.is_bank
    subj = mi.comps.subject
    has_dcf = (not bank) and _case(subj, "base") is not None
    has_norm = subj.normalized is not None

    ws_in = wb.active
    ws_in.title = SHEET_INPUTS
    _inputs_tab(ws_in, mi, s, names, bank, has_dcf, has_norm)

    if has_dcf:
        _dcf_tab(wb.create_sheet(SHEET_DCF), mi, s, names)
    elif bank:
        _bank_tab(wb.create_sheet(SHEET_BANK), mi, s, names, has_norm)
    else:
        _stub_tab(wb.create_sheet(SHEET_DCF),
                  "Insufficient FCF history for a reverse DCF — see Normalized & Football tabs.")

    if has_norm:
        _normalized_tab(wb.create_sheet(SHEET_NORM), mi, s, names)
    else:
        _stub_tab(wb.create_sheet(SHEET_NORM),
                  "Revenue / operating-margin history insufficient to normalize.")

    _football_tab(wb.create_sheet(SHEET_FOOTBALL), mi, s, names, bank, has_dcf, has_norm)

    if mi.spinoff is not None:
        _sotp_tab(wb.create_sheet(SHEET_SOTP), mi, s, names)

    _notes_tab(wb.create_sheet(SHEET_NOTES), mi, bank, has_dcf)

    for nm, (sheet, coord) in names.items():
        wb.defined_names.add(DefinedName(nm, attr_text=st.ref(sheet, coord)))

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


def _pick_spin(tracker, spinco: str | None) -> SpinoffRecord | None:
    if tracker is None or not tracker.records:
        return None
    if spinco:
        key = spinco.upper()
        for rec in tracker.records:
            if (rec.spinco_ticker or "").upper() == key or (rec.spinco_cik or "") == spinco:
                return rec
    return tracker.records[0]


def build_models(
    ticker: str,
    peers: list[str] | None = None,
    *,
    wacc: float | None = None,
    terminal_growth: float | None = None,
    forecast_years: int | None = None,
    share_basis: str = "wad",
    bank: bool | None = None,
    spinco: str | None = None,
    output_path: Path | str | None = None,
    refresh: bool = False,
    comps_result: CompsResult | None = None,
) -> ModelBuildResult:
    """Pull (via the Phase-3/4 engines), seed, and write models/<TICKER>_model.xlsx.

    Reuses ``run_comps`` for all valuation numbers and ``run_track`` for the SOTP
    SpinCo leg. ``shares`` / ``net_debt`` / ``tbv_per_share`` are read from the
    same cached FinancialsFrame the DCF used, so the workbook ties to the CLI.

    Pass ``comps_result`` to reuse an already-computed CompsResult (the pipeline
    does this so comps is run once for both the tear-sheet and the model).
    """
    ticker = ticker.upper()
    comps = comps_result if comps_result is not None else run_comps(
        ticker, peers, wacc=wacc, terminal_growth=terminal_growth,
        forecast_years=forecast_years, share_basis=share_basis,
        output_path=None, fetch_prices=True, refresh=refresh,
    )  # writes comps_<TICKER>.xlsx to the gitignored cache (harmless seed artifact)

    edgar = EdgarProvider()
    ff = edgar.get_financials(ticker, use_cache=not refresh)
    shares = _last_shares(ff)
    nd = net_debt_fy(ff).dropna()
    net_debt = float(nd.iloc[-1]) if not nd.empty else 0.0

    is_bank = comps.subject.is_bank if bank is None else bank
    tbv_ps = float("nan")
    if is_bank:
        tbv = tangible_book_value_fy(ff).dropna()
        if not tbv.empty and shares == shares and shares > 0:
            tbv_ps = float(tbv.iloc[-1]) / shares

    tracker = spin = None
    if spinco is not None:
        tracker = run_track(ticker, spinco=spinco, refresh=refresh)
        spin = _pick_spin(tracker, spinco)

    mi = ModelInputs(comps=comps, shares=shares, net_debt=net_debt,
                     tbv_per_share=tbv_ps, is_bank=is_bank, spinoff=spin)
    out = Path(output_path) if output_path else (models_dir() / f"{ticker}_model.xlsx")
    build_workbook(mi, out)
    return ModelBuildResult(ticker=ticker, xlsx_path=out, is_bank=is_bank,
                            has_sotp=spin is not None, comps_result=comps, tracker_result=tracker)
