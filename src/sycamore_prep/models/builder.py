def _football_tab(ws, mi, s, names, bank, has_dcf, has_norm) -> None:
    subj = mi.comps.subject
    st.title(ws, f"Football Field — {subj.ticker}  (valuation ranges vs price)")
    st.header_row(ws, 4, ["Method", "Low (bear)", "Mid", "High (bull)", "Mid vs price"])
    r = 5
    method_rows = []

    def method(label, lo, mid, hi):
        nonlocal r
        ws.cell(row=r, column=1, value=label)
        st.write_cell(ws, r, 2, lo, st.BEAR, st.FMT_PRICE)
        st.write_cell(ws, r, 3, mid, st.FORMULA, st.FMT_PRICE)
        st.write_cell(ws, r, 4, hi, st.FORMULA, st.FMT_PRICE)
        st.write_cell(ws, r, 5, f"=IFERROR(C{r}/PRICE-1,NA())", st.FORMULA, st.FMT_PCT)
        method_rows.append(r)
        r += 1

    if has_dcf:
        method("Reverse DCF (bear/base/bull)", "=FV_BEAR", "=FV_BASE", "=FV_BULL")
    if bank and _ok(s["tbv_ps"]):
        method("Own-history P/TBV", "=PTBV_P25*TBV_PS", "=PTBV_MEDIAN*TBV_PS", "=PTBV_P75*TBV_PS")
    if has_norm and _ok(s["pe_median"]):
        method("Own-history P/E", "=TROUGH_EPS*PE_P25", "=NORM_EPS*PE_MEDIAN", "=NORM_EPS*PE_P75")
    if has_norm and not bank and _ok(s["peer_pe_median"]):
        method("Peer P/E", "=NORM_EPS*PEER_PE_MIN", "=NORM_EPS*PEER_PE_MEDIAN", "=NORM_EPS*PEER_PE_MAX")

    # Current-price reference marker.
    r += 1
    ws.cell(row=r, column=1, value="Current price (reference)").font = Font(bold=True)
    st.write_cell(ws, r, 3, "=PRICE", st.YFINANCE, st.FMT_PRICE)

    if method_rows:
        lo_r, hi_r = method_rows[0], method_rows[-1]
        ws.conditional_formatting.add(
            f"B{lo_r}:D{hi_r}",
            DataBarRule(start_type="min", end_type="max", color="8EAADB"),
        )
    ws.cell(row=2, column=1,
            value="Each row is a valuation RANGE; data bars show relative levels. Compare to the "
                  "current-price marker. Low column (bear) first. A true floating-bar chart is a "
                  "deliberate non-goal — see MODEL_NOTES to add one.").font = Font(italic=True)
    st.set_widths(ws, {1: 30, 2: 14, 3: 14, 4: 14, 5: 14})


