"""Excel model-scaffold generator.

Produces ``models/<TICKER>_model.xlsx`` — a LEAN, rebuildable skeleton (NOT a
finished black-box model, NOT to be presented in an interview as autogenerated;
CLAUDE.md non-goal). Drivers are input cells; valuation is LIVE Excel formulas
off those drivers, so the analyst flexes assumptions IN Excel. Values are SEEDED
from the Phase-3/4 engines (``comps.run_comps`` / ``spinoffs.run_track``) — the
math is never re-implemented in Python and dumped as static numbers; the Excel
formulas mirror the engine so the reverse-DCF ties to the ``comps <TICKER>`` CLI.

Downside-first: bear is the first data column on every valuation tab and carries
the loudest styling. Source-tagged: every input is marked input / formula /
EDGAR-primary / yfinance-non-primary / analyst-assumption on the Inputs tab.

Split for testability: ``build_models`` does the (networked) data gather, then
``build_workbook`` assembles the file from a plain ``ModelInputs`` bundle — the
offline tests build a synthetic bundle and never touch the network.
"""

