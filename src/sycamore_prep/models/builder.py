def _sotp_tab(ws, mi, s, names) -> None:
    rec = mi.spinoff
    st.title(ws, f"Spin-off SOTP / Stub — {mi.comps.subject.ticker}")
    ws.cell(row=2, column=1,
            value="Sum-of-the-parts skeleton. The tracker provides only SpinCo FCF + ratios "
                  "(no segment EBITDA/shares) — so parent segments are ANALYST INPUTS. Fill amber "
                  "cells from the Form 10 information statement.").font = Font(italic=True)
    st.header_row(ws, 4, ["Part / line", "Value", "Type", "Source / note"])
    r = 5

    def line(label, value, kind, source, fmt=None, formula=False):
        nonlocal r
        if formula:
            st.write_cell(ws, r, 2, value, st.FORMULA, fmt)
        else:
            st.write_cell(ws, r, 2, value, kind, fmt)
        ws.cell(row=r, column=1, value=label)
        ws.cell(row=r, column=3, value=kind)
        ws.cell(row=r, column=4, value=source)
        out = r
        r += 1
        return out

    ws.cell(row=r, column=1, value="Parent ex-SpinCo (analyst inputs)").font = Font(bold=True, italic=True)
    r += 1
    seg_ev_rows = []
    for i in (1, 2, 3):
        re = line(f"Segment {i} EBITDA ($)", 0, st.INPUT, "analyst input (Form 10 / segments)", st.FMT_USD_M)
        rm = line(f"Segment {i} EV/EBITDA (×)", 8.0, st.INPUT, "analyst input (peer multiple)", st.FMT_MULT)
        rv = line(f"Segment {i} EV ($)", f"=B{re}*B{rm}", st.FORMULA, "EBITDA × multiple",
                  st.FMT_USD_M, formula=True)
        seg_ev_rows.append(rv)
    r_sumparent = line("Σ Parent segment EV ($)",
                       "=" + "+".join(f"B{x}" for x in seg_ev_rows), st.FORMULA, "sum of parts",
                       st.FMT_USD_M, formula=True)

    r += 1
    ws.cell(row=r, column=1, value="SpinCo (seeded from tracker where available)").font = \
        Font(bold=True, italic=True)
    r += 1
    r_scfcf = line("SpinCo FCF ($)", rec.fcf if _ok(rec.fcf) else 0, st.EDGAR,
                   "EDGAR SpinCo FCF (tracker)", st.FMT_USD_M)
    r_scmult = line("SpinCo P/FCF (×)", 15.0, st.INPUT, "analyst input", st.FMT_MULT)
    r_scval = line("SpinCo equity value ($)", f"=B{r_scfcf}*B{r_scmult}", st.FORMULA,
                   "FCF × P/FCF", st.FMT_USD_M, formula=True)
    line("SpinCo net debt/EBITDA (context)", rec.net_debt_ebitda if _ok(rec.net_debt_ebitda) else None,
         st.EDGAR, "EDGAR SpinCo (tracker)", st.FMT_MULT)
    line("SpinCo ROIC (context)", rec.roic if _ok(rec.roic) else None, st.EDGAR,
         "EDGAR SpinCo (tracker)", st.FMT_PCT)
    line("Distribution ratio (context)", rec.distribution_ratio or "pending", st.EDGAR,
         "Form 10 EX-99.1 (tracker)")

    r += 1
    ws.cell(row=r, column=1, value="Consolidated → per share").font = Font(bold=True, italic=True)
    r += 1
    r_totev = line("Total EV (parent segments) ($)", f"=B{r_sumparent}", st.FORMULA,
                   "parent stub EV", st.FMT_USD_M, formula=True)
    r_nd = line("Less: consolidated net debt ($)", "=NET_DEBT", st.FORMULA, "EDGAR (Inputs)",
                st.FMT_USD_M, formula=True)
    r_eq = line("Parent equity value (ex-SpinCo) ($)", f"=B{r_totev}-B{r_nd}", st.FORMULA,
                "EV − net debt", st.FMT_USD_M, formula=True)
    r_ps = line("Implied value / share ($)", f"=IFERROR(B{r_eq}/SHARES,NA())", st.FORMULA,
                "÷ shares", st.FMT_PRICE, formula=True)
    line("vs current price (MoS)", f"=IFERROR(B{r_ps}/PRICE-1,NA())", st.FORMULA,
         "downside-first read", st.FMT_PCT, formula=True)

    flags = ", ".join(rec.downside_flags) if rec.downside_flags else "none/pending"
    ws.cell(row=r + 1, column=1, value=f"Downside flags (tracker): {flags}").font = \
        Font(bold=True, color="C00000")
    st.set_widths(ws, {1: 36, 2: 16, 3: 18, 4: 36})


