def _ok(x) -> bool:
    """True if x is a usable finite number."""
    if x is None:
        return False
    try:
        return not (isinstance(x, float) and (math.isnan(x) or math.isinf(x)))
    except (TypeError, ValueError):
        return False


def _case(subj: TickerAnalysis, label: str):
    for c in subj.dcf_cases:
        if c.label == label:
            return c
    return None


def _peer_pe_stats(peer_table, subject_ticker: str) -> tuple[float, float, float]:
    """min / median / max P/E across the *individual* peers (excludes the subject
    and the PEER_MEDIAN / PEER_MEAN summary rows). Real peer range for the
    football field."""
    if peer_table is None or peer_table.empty or "pe" not in peer_table.columns:
        return (float("nan"),) * 3
    drop = {subject_ticker, "PEER_MEDIAN", "PEER_MEAN"}
    peers = peer_table[~peer_table.index.isin(drop)]
    pe = peers["pe"].dropna()
    if pe.empty:
        return (float("nan"),) * 3
    return float(pe.min()), float(pe.median()), float(pe.max())


def _seeds(mi: ModelInputs) -> dict:
    """Flatten the engine outputs into the scalar seeds the cells read from."""
    subj = mi.comps.subject
    norm = subj.normalized
    base, bear, bull = _case(subj, "base"), _case(subj, "bear"), _case(subj, "bull")
    bands = subj.history.bands if subj.history else {}
    pe = bands.get("PE")
    ptbv = bands.get("P_TBV")
    p_min, p_med, p_max = _peer_pe_stats(mi.comps.peer_table, subj.ticker)
    return {
        "wacc": mi.comps.wacc,
        "tg": mi.comps.terminal_growth,
        "years": int(mi.comps.forecast_years),
        "tax": norm.tax_rate if norm else DEFAULT_TAX_RATE,
        "price": subj.price,
        "mcap": subj.market_cap,
        "shares": mi.shares,
        "net_debt": mi.net_debt,
        "fcff0_base": base.fcf0 if base else float("nan"),
        "fcff0_bear": bear.fcf0 if bear else float("nan"),
        "fcff0_bull": bull.fcf0 if bull else float("nan"),
        "assumed_g": base.assumed_growth if base else float("nan"),
        "implied_g_base": base.implied_growth if base else float("nan"),
        "implied_g_bear": bear.implied_growth if bear else float("nan"),
        "implied_g_bull": bull.implied_growth if bull else float("nan"),
        "revenue": norm.current_revenue if norm else float("nan"),
        "mean_opm": norm.mean_op_margin if norm else float("nan"),
        "trough_opm": norm.trough_op_margin if norm else float("nan"),
        "int_exp": norm.interest_expense if norm else float("nan"),
        "trailing_pe": norm.trailing_pe if norm else float("nan"),
        "tbv_ps": mi.tbv_per_share,
        "pe_p25": pe.p25 if pe else float("nan"),
        "pe_median": pe.median if pe else float("nan"),
        "pe_p75": pe.p75 if pe else float("nan"),
        "ptbv_p25": ptbv.p25 if ptbv else float("nan"),
        "ptbv_median": ptbv.median if ptbv else float("nan"),
        "ptbv_p75": ptbv.p75 if ptbv else float("nan"),
        "peer_pe_min": p_min,
        "peer_pe_median": p_med,
        "peer_pe_max": p_max,
    }


