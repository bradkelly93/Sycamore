def _case_row(ws, row, label, formulas, kind=st.FORMULA, fmt=None, bear=False):
    ws.cell(row=row, column=1, value=label)
    for i, f in enumerate(formulas):
        k = st.BEAR if (i == 0 and bear) else kind
        st.write_cell(ws, row, 2 + i, f, k, fmt)


def _dcf_tab(ws, mi, s, names) -> None:
    subj = mi.comps.subject
    st.title(ws, f"DCF & Reverse-DCF — {subj.ticker}")
    n = max(1, int(s["years"]))

    r_wacc, r_tg, r_fcff0, r_assumed = 5, 6, 7, 8
    st.header_row(ws, 4, ["Driver", "Bear (downside)", "Base", "Bull"])
    _case_row(ws, r_wacc, "WACC",
              ["=WACC+WACC_STRESS", "=WACC",
               "=MAX(WACC-WACC_STRESS,TERM_G+TG_STRESS+0.005)"], fmt=st.FMT_PCT, bear=True)
    _case_row(ws, r_tg, "Terminal growth",
              ["=MAX(TERM_G-TG_STRESS,0)", "=TERM_G", "=TERM_G+TG_STRESS"],
              fmt=st.FMT_PCT, bear=True)
    _case_row(ws, r_fcff0, "FCFF₀ ($)", ["=FCFF0_BEAR", "=FCFF0_BASE", "=FCFF0_BULL"],
              fmt=st.FMT_USD_M, bear=True)
    _case_row(ws, r_assumed, "Assumed FCFF growth (fwd)", ["=ASSUMED_G"] * 3,
              kind=st.ASSUMPTION, fmt=st.FMT_PCT)

    strip_start = 12
    st.header_row(ws, strip_start - 1, ["Year", "Bear", "Base", "Bull"])
    for k in range(n):
        r = strip_start + k
        ws.cell(row=r, column=1, value=k + 1)
        for i, c in enumerate(CASE_COLS):
            f = (f"=IF($A{r}<=YEARS,{c}${r_fcff0}*(1+ASSUMED_G)^$A{r}"
                 f"/(1+{c}${r_wacc})^$A{r},0)")
            st.write_cell(ws, r, 2 + i, f, st.FORMULA, st.FMT_USD_M)
    strip_end = strip_start + n - 1

    r_sumpv = strip_end + 1
    r_pvtv = r_sumpv + 1
    r_ev = r_pvtv + 1
    r_nd = r_ev + 1
    r_eq = r_nd + 1
    r_fv = r_eq + 1
    r_mos = r_fv + 1

    _case_row(ws, r_sumpv, "Σ PV of explicit FCFF",
              [f"=SUM({c}{strip_start}:{c}{strip_end})" for c in CASE_COLS], fmt=st.FMT_USD_M)
    _case_row(ws, r_pvtv, "PV of terminal value",
              [(f"=IF({c}${r_wacc}>{c}${r_tg},{c}${r_fcff0}*(1+ASSUMED_G)^YEARS"
                f"*(1+{c}${r_tg})/({c}${r_wacc}-{c}${r_tg})/(1+{c}${r_wacc})^YEARS,NA())")
               for c in CASE_COLS], fmt=st.FMT_USD_M)
    _case_row(ws, r_ev, "Enterprise value",
              [f"={c}{r_sumpv}+{c}{r_pvtv}" for c in CASE_COLS], fmt=st.FMT_USD_M)
    _case_row(ws, r_nd, "Less: net debt", ["=NET_DEBT"] * 3, fmt=st.FMT_USD_M)
    _case_row(ws, r_eq, "Equity value",
              [f"={c}{r_ev}-{c}{r_nd}" for c in CASE_COLS], fmt=st.FMT_USD_M)
    _case_row(ws, r_fv, "Fair value / share",
              [f"=IFERROR({c}{r_eq}/SHARES,NA())" for c in CASE_COLS],
              fmt=st.FMT_PRICE, bear=True)
    _case_row(ws, r_mos, "Margin of safety vs price",
              [f"=IFERROR({c}{r_fv}/PRICE-1,NA())" for c in CASE_COLS],
              fmt=st.FMT_PCT, bear=True)

    names["FV_BEAR"] = (SHEET_DCF, f"B{r_fv}")
    names["FV_BASE"] = (SHEET_DCF, f"C{r_fv}")
    names["FV_BULL"] = (SHEET_DCF, f"D{r_fv}")

    # Downside-first banner (bear first), referencing the MoS row.
    banner = (f'="Bear-case MoS  "&IFERROR(TEXT(B{r_mos},"0.0%"),"n/a")'
              f'&"      Base  "&IFERROR(TEXT(C{r_mos},"0.0%"),"n/a")'
              f'&"      Bull  "&IFERROR(TEXT(D{r_mos},"0.0%"),"n/a")')
    bc = ws.cell(row=2, column=1, value=banner)
    bc.font = Font(bold=True, color="C00000")

    # ---- Reverse DCF: implied growth + tie-out check ----
    r_rev = r_mos + 2
    ws.cell(row=r_rev, column=1,
            value="Reverse DCF — growth priced in (tie-out)").font = Font(bold=True, italic=True)
    st.header_row(ws, r_rev + 1, ["", "Bear", "Base", "Bull"])
    r_impg = r_rev + 2
    r_evimp = r_impg + 1
    r_curr = r_evimp + 1
    r_resid = r_curr + 1

    _case_row(ws, r_impg, "Implied FCFF growth (priced in)",
              ["=IMPLIED_G_BEAR", "=IMPLIED_G_BASE", "=IMPLIED_G_BULL"],
              kind=st.SEED, fmt=st.FMT_PCT)
    ig_names = ["IMPLIED_G_BEAR", "IMPLIED_G_BASE", "IMPLIED_G_BULL"]
    evimp = []
    for c, ig in zip(CASE_COLS, ig_names):
        w, tg, f0 = f"{c}{r_wacc}", f"{c}{r_tg}", f"{c}{r_fcff0}"
        x = f"((1+{ig})/(1+{w}))"
        explicit = f"{f0}*{x}*(1-{x}^YEARS)/(1-{x})"
        tv = f"{f0}*(1+{ig})^YEARS*(1+{tg})/({w}-{tg})/(1+{w})^YEARS"
        evimp.append(f"=IFERROR({explicit}+{tv},NA())")
    _case_row(ws, r_evimp, "EV @ implied growth (check)", evimp, fmt=st.FMT_USD_M)
    _case_row(ws, r_curr, "Current EV (mkt cap + net debt)", ["=MKT_CAP+NET_DEBT"] * 3,
              fmt=st.FMT_USD_M)
    _case_row(ws, r_resid, "Tie-out residual (≈ 0)",
              [f"={c}{r_evimp}-{c}{r_curr}" for c in CASE_COLS], fmt=st.FMT_USD_M)

    # Green when residual is within 0.5% of current EV (i.e. it ties out).
    green = PatternFill("solid", fgColor="C6EFCE")
    ws.conditional_formatting.add(
        f"B{r_resid}:D{r_resid}",
        FormulaRule(formula=[f"ABS(B{r_resid})<0.005*B{r_curr}"], fill=green),
    )
    ws.cell(row=r_resid + 2, column=1,
            value="Seeded implied growth ties EV→current EV on open (residual≈0). After flexing "
                  "WACC/TG/FCFF₀: Data ▸ What-If ▸ Goal Seek — Set the residual cell To 0 By "
                  "changing the matching IMPLIED_G_* input. (Engine: reverse_dcf.solve_implied_growth.)")
    st.set_widths(ws, {1: 34, 2: 16, 3: 16, 4: 16})


