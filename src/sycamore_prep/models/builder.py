def _normalized_tab(ws, mi, s, names) -> None:
    subj = mi.comps.subject
    st.title(ws, f"Normalized / Mid-cycle Earnings — {subj.ticker}")
    st.header_row(ws, 4, ["Line (per share unless noted)", "Trough (downside)", "Mid-cycle"])
    r0 = 5
    rows = [
        ("Operating margin", "=TROUGH_OPM", "=MEAN_OPM", st.FMT_PCT, True),
        ("× Current revenue ($)", "=REVENUE", "=REVENUE", st.FMT_USD_M, False),
        ("Operating income ($)", "=TROUGH_OPM*REVENUE", "=MEAN_OPM*REVENUE", st.FMT_USD_M, False),
        ("Less: interest expense ($)", "=INT_EXP", "=INT_EXP", st.FMT_USD_M, False),
        ("Net income after tax ($)", "=(TROUGH_OPM*REVENUE-INT_EXP)*(1-TAX)",
         "=(MEAN_OPM*REVENUE-INT_EXP)*(1-TAX)", st.FMT_USD_M, False),
        ("Diluted shares", "=SHARES", "=SHARES", st.FMT_INT, False),
        ("EPS ($)", "=IFERROR((TROUGH_OPM*REVENUE-INT_EXP)*(1-TAX)/SHARES,NA())",
         "=IFERROR((MEAN_OPM*REVENUE-INT_EXP)*(1-TAX)/SHARES,NA())", st.FMT_PRICE, True),
        ("Price ($)", "=PRICE", "=PRICE", st.FMT_PRICE, False),
        ("P/E", "=IFERROR(PRICE/B{eps},NA())", "=IFERROR(PRICE/C{eps},NA())", st.FMT_MULT, True),
    ]
    r_eps = r0 + 6  # EPS row index (0-based 6th entry)
    for k, (label, fb, fc, fmt, bear) in enumerate(rows):
        r = r0 + k
        fb = fb.replace("{eps}", str(r_eps))
        fc = fc.replace("{eps}", str(r_eps))
        _case_row(ws, r, label, [fb, fc], fmt=fmt, bear=bear)
    r_pe = r0 + 8

    names["TROUGH_EPS"] = (SHEET_NORM, f"B{r_eps}")
    names["NORM_EPS"] = (SHEET_NORM, f"C{r_eps}")

    # Trailing P/E reference (seeded; not reconstructable from drivers).
    r_tr = r_pe + 2
    ws.cell(row=r_tr, column=1, value="Trailing P/E (as-reported EpsDiluted, reference)")
    st.write_cell(ws, r_tr, 2, s["trailing_pe"], st.SEED, st.FMT_MULT)

    banner = (f'="Trough (downside) P/E  "&IFERROR(TEXT(B{r_pe},"0.00")&"x","n/a")'
              f'&"      Mid-cycle P/E  "&IFERROR(TEXT(C{r_pe},"0.00")&"x","n/a")')
    bc = ws.cell(row=2, column=1, value=banner)
    bc.font = Font(bold=True, color="C00000")
    st.set_widths(ws, {1: 38, 2: 18, 3: 18})


